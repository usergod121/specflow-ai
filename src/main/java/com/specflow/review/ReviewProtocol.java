package com.specflow.review;

/**
 * 检查阶段的协议说明——会被逐字拼进系统提示词。
 *
 * <p>和 {@link com.specflow.context.PatchProtocol} 一样单独成类：
 * 这段文字是<b>引擎与模型之间的接口契约</b>，必须和 {@link PlanParser} 的解析规则同步演进。
 *
 * <p>为什么用分块标记而不是让模型回 JSON：模型对「照抄这几个标记」的执行力，
 * 明显强于「输出合法 JSON」。而且标记块天然容忍前后夹杂的解释性文字，
 * 解析器只要逐行扫描即可，不需要考虑转义和嵌套。
 */
public final class ReviewProtocol {

    private ReviewProtocol() {
    }

    public static final String SUMMARY_MARKER = "<<<<<<< SUMMARY";
    public static final String FLOW_MARKER = "<<<<<<< FLOW";
    public static final String MISSING_MARKER = "<<<<<<< MISSING";
    public static final String STEPS_MARKER = "<<<<<<< STEPS";
    public static final String END_SUFFIX = ">>>>>>>";

    /** 缺失清单里表示「什么都不缺」的写法。 */
    public static final String NOTHING_MISSING = "无";

    /**
     * 施工单那一行怎么写，以及为什么这么要求。
     *
     * <p>单独抽出来是因为它有两个消费者：完整检查协议，和「只产施工单」的
     * {@link StepsProtocol}。同一件事的规矩写两遍，两个入口迟早会拆出两种风格的步子，
     * 而引擎按同一套规则去执行它们。
     */
    public static final String STEPS_RULES = """
            <序号> | <这一步做什么> | <涉及文件（逗号分隔，必须来自目标清单）> | <怎么算做完> | <自洽或中间态>

            施工单怎么写（它决定后面干活时能不能一步接一步走顺，写不准比不写更麻烦）：
            - 每行一步，从 1 开始编号，按执行顺序写；五个字段用竖线 | 分隔，不要加粗、
              也不要在单元格外写字。
            - 第 3 栏必须逐个来自目标文件清单（多个用逗号分隔；清单里还没建的文件也算）。
              写了清单外的文件，这一步执行不了，机器会把它当场拦下来。
            - 第 4 栏写「怎么算做完」，要让不懂这块的人也能照着验：项目能编译通过、
              查不到时返回空而不是抛异常、某个接口能返回组装好的结果。
              不要写「完成 XXX 功能」这种等于没写的。
            - 第 5 栏只能填两种值：
              * 自洽 —— 这一步做完，整个项目还能编译（**默认都该是它**）；
              * 中间态 —— 这一步做完项目**可能编译不过**，只有确实做不到自洽时才写，
                并在第 4 栏说清「哪一部分还没接上」。
            - **按功能切，不要按层切**：别写成「先写完所有 Entity、再写完所有 Service、
              最后写 Controller」——那样每一步都编不过。要写成「一个功能从入口到落地一次打通」。
            - 最后一步不许标中间态；中间态不超过总步数的三分之一。
            - 步数 3 到 7 步，越少越好：每一步都要重新装配一次上下文、重跑一次编译。

            样例（三步，注意第 5 栏的变化）：
            1 | 给 Foo 加一个按编号查询的方法，查不到返回空集合 | src/main/java/demo/Foo.java | Foo 能编译，且查不到时返回空集合而不是抛异常 | 自洽
            2 | 让 BarService 调用上面那个方法并组装结果 | src/main/java/demo/BarService.java, src/main/java/demo/Foo.java | BarService 能编译，查询返回组装好的结果 | 自洽
            3 | 在控制层把这个查询暴露出去 | src/main/java/demo/FooController.java | 项目整体编译通过，接口路径与已有接口风格一致 | 自洽
            """;

    /** 为什么要拆步——两个协议都要讲，因为它直接决定模型愿不愿意认真拆。 */
    public static final String STEPS_WHY = """
            为什么要拆：每一步做完都会跑一次编译。整个项目一起编译时，任何一个文件断了就是整次失败，
            所以「加接口 → 加实现 → 改调用点」这种必须的顺序里天然会出现编不过的中间状态——
            能自洽就自洽，做不到就明说「中间态」，别硬凑。
            """;

    public static final String INSTRUCTIONS = """
            现在进入「检查」阶段。你不要写代码，只需回答一个问题：
            基于已有的信息，这个需求你能不能做？打算怎么做？

            按下面的格式输出，块之间不要写解释性文字：

            %s
            用一两句话说明你打算怎么实现。
            %s SUMMARY

            %s
            flowchart TD
                A[入口：用户怎么触发] --> B{关键判断}
                B -->|否定分支| C[怎么处理]
                B -->|肯定分支| D[主要处理步骤]
                subgraph 数据层
                  D --> E[查库或写库]
                end
                E --> F[返回什么]
            %s FLOW

            %s
            <缺什么> | <严重度> | <影响（技术）> | <影响（业务）> | <建议默认值>
            %s MISSING

            %s
            %s
            %s STEPS

            流程图只认下面这些写法（多写的会被忽略，等于图缺了一块）：
            - 第一行必须是 `flowchart TD`，整段只有一个图表头。
            - 节点：`A[矩形]`、`B{判断}`、`C(圆角)`、`D((圆))`、`E[(数据库)]`、`F{{六边形}}`、`G>旗形]`；
              标签里可以有中文、空格和 `<br/>`（换行），要写竖线就用引号括起来：`A["a | b"]`。
            - 连线：`-->`（实线箭头）、`---`（实线）、`-.->`（虚线箭头）、`==>`（粗线箭头）；
              分支标签写在箭头后面：`B -->|是| C`；一个节点连多个用 `&`：`A --> B & C`。
            - 分组：`subgraph 组名` 到 `end`，把属于同一模块的步骤框在一起（别嵌套）。
            - 不要写 `classDef`、`style`、`linkStyle`、`click`、颜色：这些一律被忽略，还会让人以为
              图缺了一块。想表达区别就用节点文字说清楚，别指望样式。
            - 节点不超过 12 个；每个节点都要连进主链路（不要出现谁都不连的孤立框）；
              一个判断的两条分支都要画出来并标上文字。
            - **清单之外的文件你动不了**（新建也不行）。所以别把图画成「新建某个清单外的类」：
              要么用清单里的文件做得到的事就按清单做，要么在 MISSING 里写清「需要把 X 加进目标文件」。

            MISSING 块怎么写（这一块决定用户要不要停下来补东西，写不准比不写更烦人）：
            - 每行一条，五个字段用竖线 `|` 分隔，不要编号、不要加粗、不要写单元格外的话。
            - 判严重度只问两个问题：**我猜得动吗？猜错要返工吗？**
              * 两条同时成立 → 写「阻断」：项目里查不到依据（只能猜），而且猜错了，要么做出来的东西
                不是用户要的（需求要导出 Excel，你只能给 CSV），要么**这个选择会被后面所有代码跟着抄**
                （项目里没有统一的返回结构、分页约定、错误码规范，你一旦自己发明一套，
                整个模块以后都会按你这套写下去）。这两种都必须用户先表态，否则这一轮要么白做、
                要么做出个「不是他要的东西」。
              * 猜错改几行就能回来的一次性选择 → 写「影响质量」：字段名、方法签名、边界值、报错文案。
                照现有代码的风格写基本不会错，先按你的默认值写、在注释里写明假设即可。
              * 不做也完全不影响这次能不能交出来 → 写「可选」：日志文案、注释风格。
            - 「影响（技术）」写给懂这块的人（一两句，说清会坏在哪）；
              「影响（业务）」写给不熟这块的人（说清最终用户会看到什么差别）。两栏都要有。
            - 「建议默认值」栏写你打算怎么办，并且要和严重度对得上：标「阻断」的，这一栏要写清
              「按我猜的做下去会变成什么」；标「影响质量/可选」的，就照项目里已有的写法写具体做法。
            - 每条都要是「不做这一条的具体后果」，不要写「建议补充更多上下文」这种空话。
            - 最多 5 条，而且能自己推断的不许列。宁可少列一条，也不要把用户没说的东西都问一遍。
            - 三档都要真的用起来：如果列出来清一色是「阻断」，回头看看里面有没有其实是
              「影响质量」的——把字段名、边界值这类当成阻断，会让人每次都停下来回你话。

            对与不对的例子（照上面五栏的格式）：
              你项目里统一的接口返回结构 | 阻断 | 项目里没有统一响应包装，我一旦自己发明一套，后面每个接口都会跟着它写 | 前端拿到的字段和别处不一样，联调要到处改 | 先自己定义 Result{code,msg,data}（等于替你定下了整个项目的接口风格）
              orders 表的所有字段 | 阻断 | 不看表结构只能猜列名和类型，写出来的映射大概跑不通 | 订单查询会用错列，功能直接不可用 | 猜一套字段先写（等于把这次的需求改成「先能跑」）
              DTO 字段的命名习惯 | 影响质量 | 能编译，但字段名可能和你项目里的风格不一致 | 界面显示的字段名对不上你要的叫法 | 照现有代码里的驼峰命名写
              错误码的具体取值 | 可选 | 用 400 也能跑通 | 报错文案可能和你们线上已有的规范不一样 | 统一用 400 + 中文提示
              需要新建一个 Controller 才有接口层，但目标文件里没有它 | 阻断 | 清单外的文件我改不了，接口这一层写不出来 | 这次需求里的接口做不出来，只能给你一堆底层代码 | 需要把 src/main/java/.../XxxController.java 加进目标文件
              建议补充更多上下文 | （这种不要写） | 它没说缺什么、要什么、缺了会怎样 | 用户看完不知道该干什么 | 无

            硬性规则：
            1. 流程图只能有一个入口节点，整体自上而下走通，不要画交叉连线。
            2. 节点文字要短（不超过 25 个字），说清楚「做什么」即可，不要贴代码。
            3. 你要按本次实际给你的目标文件来画，不要凭空设想还不存在的类。
            4. 若你认为信息已经足够，MISSING 块只写一行：%s
            5. 你写完方案之后，机器会再核一遍：方案里提到、而目标文件清单里没有的文件，
               会被当成「这套方案执行不了」提示给用户。所以别把清单外的新文件当成方案的正常一步；
               真需要，就在 MISSING 里写清「需要把 X 加进目标文件」。
            6. **动手之前先把自己实现这个需求所需要的输入列全**：要参照哪个文件、要确认哪个设计选择，
               缺什么就写进 MISSING 块。**别留到开发阶段再说**——那时用户已经付过两次调用的钱，
               而开发阶段一喊缺，这一轮就白跑了。信息真够的话，MISSING 就只写一行：%s
            7. 施工单（STEPS 块）是**必须**的，而且会被机器逐条核一遍：步数越界、
               最后一步标了中间态、第 3 栏写了目标清单外的文件，都会被拦下来要求改。
               这几条不是格式要求，是「照着做会卡住」的硬事实。

            注意 SUMMARY / MISSING 两块在内容为空时可以省略，FLOW 与 STEPS 两块必须给出。
            """.formatted(SUMMARY_MARKER, END_SUFFIX,
            FLOW_MARKER, END_SUFFIX,
            MISSING_MARKER, END_SUFFIX,
            STEPS_MARKER, STEPS_RULES, END_SUFFIX, STEPS_WHY,
            NOTHING_MISSING, NOTHING_MISSING);
}
