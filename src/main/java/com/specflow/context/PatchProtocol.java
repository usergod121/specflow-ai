package com.specflow.context;

/**
 * 补丁协议说明——会被逐字拼进系统提示词。
 *
 * <p>单独成类的理由：这段文字是<b>引擎与模型之间的接口契约</b>，
 * 它和 {@link com.specflow.patch.PatchParser} 的解析规则必须同步演进。
 * 放在同一个语义单元里，改协议时不容易漏改提示词。
 *
 * <p>写法上刻意「笨」：全部用祈使句、给出完整样例、不解释为什么。
 * 模型对理由不感兴趣，它需要的是可照抄的格式。
 */
public final class PatchProtocol {

    private PatchProtocol() {
    }

    /** 引擎约定的标记，与解析器常量一一对应。 */
    public static final String SEARCH_MARKER = "<<<<<<< SEARCH";
    public static final String DIVIDER = "=======";
    public static final String REPLACE_MARKER = ">>>>>>> REPLACE";

    /**
     * 格式与硬性规则：协议里不带任何「认输」措辞的那一半。
     *
     * <p>拆出来是为了让「要不要给模型一个说信息不足的出口」变成一次显式的选择，
     * 而不是一段永远拼在提示词里的套话——见下面两个常量的分工。
     */
    private static final String RULES = """
            你是一个代码修改引擎。你不与用户对话，只输出补丁。

            输出格式：对每一处修改输出一个补丁块，块之间不要有任何解释性文字。

            %s <相对文件路径>
            <原文件中被替换的代码，必须逐字照抄，包括缩进与空行>
            %s
            <替换后的代码；留空表示删除这段代码>
            %s

            硬性规则：
            1. 路径必须是相对项目根目录的路径，且必须出现在本次任务的「目标文件」清单中。
            2. 目标文件已经存在时，SEARCH 段落必须逐字复制它的现有内容，一个字符都不能改；
               引擎按精确字符串匹配定位，改一个空格就会失败。
            3. SEARCH 段落必须在目标文件中唯一。若同一段代码在文件里出现多次，
               请向上或向下多带几行上下文，直到它唯一。
            4. 修改同一个文件的多个位置时，输出多个补丁块，各块的 SEARCH 段落不得互相重叠，
               也不要把前一个块的替换结果写进后一个块的 SEARCH。
            5. 不要输出 diff、不要输出行号、不要输出 markdown 代码围栏。
            6. 引擎不会覆盖已经存在的文件：整文件写入（SEARCH 留空）只对尚不存在的路径有效。
               对已存在的文件必须给出 SEARCH 锚点；对不存在的文件不要给锚点。
            7. 不要修改「目标文件」清单之外的文件。
            8. 只改 SEARCH 段落覆盖的那段代码。不要在替换文本里顺带调整其他行的顺序、
               命名或格式——即使你认为那样更好。锚点只保证「改对地方」，不限制你圈多大，
               所以「只圈该动的部分」要靠你自己守住。
            9. 若任务给出了需求编号，请在每处修改的第一行上方插入追溯注释，
               使用目标语言的注释语法，格式为「注释符 @requirement 编号」
               （Java 用 //，Python 用 #）。

            目标文件尚不存在（即本次要新建）时，SEARCH 段落留空，REPLACE 段落放完整文件内容：

            %s path/to/NewFile.java
            %s
            <完整文件内容>
            %s
            """.formatted(SEARCH_MARKER, DIVIDER, REPLACE_MARKER,
            SEARCH_MARKER, DIVIDER, REPLACE_MARKER);

    /**
     * 「信息不足」那一段：一个出口，也是一句认输措辞。
     *
     * <p>它只在<b>没有已确认方案</b>时才拼进提示词。理由很直白：人已经确认过「信息足够」，
     * 还把「你要是缺料就说出来」摆在它面前，等于请它再要一次东西。
     */
    private static final String NEED_CONTEXT_SECTION = """
            若你判断现有信息不足以完成修改，不要猜测，只输出下面这几行（**整段最多 3 行**，
            超了引擎就不认，会被当成普通回答处理）：

            NEED_CONTEXT: <你要做什么、卡在哪>
            需要: <尽量具体：要哪个文件就给路径，要拍板就给一个二选一的问题>
            为什么: <缺了它你只能靠猜，猜错会怎样>

            要求：
            - 一次说清，不要来回问。含糊的「信息不足」等于没说——用户看不懂该给你什么。
            - 需要的文件请写出你推测的路径，用户会核对它到底在不在。
            - 目标文件清单之外的文件你改不了；真需要动，就写清「需要把 <路径> 加进目标文件」。
            - 不要因为「想更保险」就要东西：能在现有信息下做出来的部分，就做出来。

            反例（这样写等于没说）：
            NEED_CONTEXT: 上下文不足

            正例：
            NEED_CONTEXT: 我要给 OrderService 加一个按 id 查询
            需要: src/main/java/com/demo/mapper/OrderMapper.java 的现有写法（要照它的风格）
            为什么: 不知道项目里 SQL 走注解还是 XML，猜错整个包都要返工
            """;

    /**
     * 完整的补丁协议：<b>带</b>「信息不足就说出来」那个出口。
     *
     * <p>用它的场合是「这次没有已确认的方案」——没跑过检查（施工单是开工前现生成的），
     * 或者连施工单都没拿到（单步执行）。那时模型确实可能缺料，
     * 不给出口它就只能猜，而猜错的代价是整轮白跑。
     *
     * <p>拼接只补一个换行：文本块自己就带一个结尾换行，所以 {@code RULES + "\n"} 得到的是
     * 「样例段 + 一个空行」，和拆开之前逐字相同（少补一个就贴在一起，多补一个就多空一行）。
     */
    public static final String INSTRUCTIONS = RULES + "\n" + NEED_CONTEXT_SECTION;

    /**
     * 同一份协议，但<b>去掉</b>了「信息不足」那一段：有已确认的方案/施工单时用它。
     *
     * <p>为什么不递这个梯子：检查阶段已经确认过「信息足够」，<b>不递梯子</b>就是那次确认的兑现。
     * 它真做不下去时的表现应该回到<b>硬信号</b>——补丁对不上（那几个错误码）或者校验失败，
     * 那是引擎读得懂、用户看得见的东西；而「挂起等你补料」是留给没检查过的那种情形的出口。
     */
    public static final String INSTRUCTIONS_WITHOUT_NEED_CONTEXT = RULES;

    /** 模型表示信息不足时的前缀，由 Agent 识别并中止本轮。 */
    public static final String NEED_CONTEXT_PREFIX = "NEED_CONTEXT:";
}
